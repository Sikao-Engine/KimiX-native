def test_ascii_gate_is_documented():
    """Non-ASCII input is out of contract for these kernels (ASCII gate).

    The reference's callers gate with ``str.isascii()`` before using the native
    kernels (``safety.py``: ``_native_use_native("TOOLS") and command.isascii()``),
    so an ungated non-ASCII call may differ.  This test *pins* the differences
    instead of hiding them:

    * ``find_error_line_index`` uses ASCII ``\\b`` word boundaries while Python's
      ``re`` uses Unicode boundaries -- ``"اnot foundا"`` (Arabic letter alef)
      matches natively but not in the reference.
    * the safety kernels short-circuit to "not blocked" for non-ASCII, so
      kimi-agent's own ``"vite \\u00e9"`` guidance vector differs.
    * ``_read_shell_word``/``lstrip()`` treat Unicode whitespace (``\\xa0``) as
      space in Python but not in the ASCII-only scanner.
    """
    command = "اnot foundا"
    assert common._find_error_line_index(command) is None      # Unicode \b
    assert SHELL.find_error_line_index(command) == 1           # ASCII \b
    assert SHELL.check_hardline_blocked("rm -rf /\u00a0") == (False, None)
    assert SHELL.foreground_background_guidance("npm run dev\u00a0") is None
    # kimi-agent's own non-ASCII guidance vector ("vite \u00e9").
    non_ascii_guidance = [c for c in _AGENT_GUIDANCE if not str(c).isascii()]
    for item in non_ascii_guidance or ["vite \u00e9"]:
        assert SHELL.foreground_background_guidance(item) is None
    # Non-breaking space is whitespace to Python, data to the ASCII scanner.
    assert py_maybe_rewrite("\u00a0git status", True, rtk_path=RTK_BINARY) == \
        ("\u00a0rtk git status", True)
    assert cpp_maybe_rewrite("\u00a0git status", True, rtk_path=RTK_BINARY) == \
        ("\u00a0git status", False)
    # ASCII input is exact, including the same characters via escapes.
    assert SHELL.find_error_line_index("not found") == \
        common._find_error_line_index("not found") == 1

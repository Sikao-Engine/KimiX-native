"""Differential parity tests for the bash builtin tool (kimix-base <-> kimi-agent).

``src/builtin_tools/bash_tool.cpp`` is a port of kimi-agent's bash tool.  This
module compares every kernel the ``runtime_py`` extension exposes through
``runtime_py.builtin_tools.shell`` against the *original* implementation in the
kimi-agent checkout (``C:/dev/kimi-agent``, override with ``KIMI_AGENT_ROOT``):

* RTK rewrite scanner -- ``common.py`` ``_split_shell_segments`` /
  ``_read_shell_word`` / ``_rewrite_shell_segment`` / ``_is_known_rtk_command`` /
  ``_maybe_rewrite_shell_command_with_rtk`` (FOCUS 1).  A silent divergence here
  changes the command that actually runs, so the corpus is adversarial and
  fuzzed with a fixed seed.
* ``fix_bash_command`` -- not exposed to Python (only C++ can call it); it is
  covered by the generated byte-exact vectors in
  ``tests/unit/builtin_tools/bash_fix_goldens.inc`` +
  ``bash_rtk_goldens.inc`` and the Boost.UT target ``test_builtin_bash``, both
  regenerated from the reference by ``scripts/gen_bash_fix_data.py``.
* Output kernels -- ``output_enhance.py`` (``interpret_exit_code``,
  ``is_expected_exit``, ``annotate_failure``) and ``common.py``
  (``_find_error_line_index``, ``_truncate_lines``), byte-exact messages.
* Safety kernels -- ``safety.py`` ``command_detection_variants`` /
  ``check_hardline_blocked`` / ``foreground_background_guidance``.

Provenance rules (learned the hard way):

* The pure-Python bodies of ``safety.py`` / ``output_enhance.py`` live in
  ``<kimi-agent>/bin/kimix_native/tools.py`` (the ``_compat_*`` functions) and
  are what kimi-agent runs when its native gate is off.  They are loaded *by
  path* from the kimi-agent checkout so that neither ``kimix_native`` on
  ``sys.path`` (the kimix-base mirror) nor a shared ``sys.modules`` entry can
  silently substitute the wrong implementation.
* ``kimix.tools.common`` (RTK + truncation + error-line kernels) is pure Python
  in the reference checkout; its four quote helpers delegate to
  ``_shell_compat.py``, which is pinned to the kimi-agent copy as well.
* ``detect_self_kill``/``self_kill_hint`` are owned by the pwsh tool and are not
  covered here.

Non-ASCII input: every kernel below is exact for ASCII only -- that is the
project-wide ASCII-gate convention, and the reference's own callers gate on
``str.isascii()`` (``safety.py`` ``_native_use_native("TOOLS") and
command.isascii()``).  ``test_ascii_gate_is_documented`` pins the two places
where an ungated non-ASCII call would differ.
"""


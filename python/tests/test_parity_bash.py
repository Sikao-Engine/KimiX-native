def test_reference_public_api_delegates_to_the_compat_bodies():
    """kimi-agent's public shell APIs dispatch to the ``_compat_*`` bodies.

    Verified on the source (works regardless of which ``kimix``/``kimix_native``
    a session already imported): each public function references its
    ``_compat_*`` counterpart, so the bodies compared above are exactly what
    kimi-agent runs on its pure-Python path.
    """
    import ast

    pairs = {
        KIMIX_SRC / "kimix" / "tools" / "file" / "bash" / "safety.py": [
            ("command_detection_variants", "_compat_command_detection_variants"),
            ("detect_hardline_command", "_compat_detect_hardline_command"),
            ("check_hardline_blocked", "_compat_check_hardline_blocked"),
            ("foreground_background_guidance",
             "_compat_foreground_background_guidance"),
        ],
        KIMIX_SRC / "kimix" / "tools" / "file" / "bash" / "output_enhance.py": [
            ("interpret_exit_code", "_compat_interpret_exit_code"),
            ("is_expected_exit", "_compat_is_expected_exit"),
            ("annotate_failure", "_compat_annotate_failure"),
        ],
    }
    for path, mapping in pairs.items():
        assert path.is_file(), path
        source = path.read_text(encoding="utf-8")
        tree = ast.parse(source)
        assert source.count("isascii()") >= 1  # the documented ASCII gate
        bodies = {node.name: ast.dump(node) for node in tree.body
                  if isinstance(node, ast.FunctionDef)}
        for public, compat in mapping:
            assert public in bodies, (path.name, public)
            assert compat in bodies[public], (path.name, public, compat)



def _seeded_split_corpus(count: int, seed: int) -> list[str]:
    rng = random.Random(seed)
    out: list[str] = []
    for _ in range(count):
        parts = []
        for _ in range(rng.randint(1, 7)):
            parts.append(rng.choice(_SPLIT_TOKENS))
            if rng.random() < 0.6:
                parts.append(rng.choice(_SPLIT_PIECES))
        out.append("".join(parts))
    return out



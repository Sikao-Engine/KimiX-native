def _load_kimi_agent_corpora() -> dict:
    """Corpora from kimi-agent's own ``tests/native/test_shell_security_equivalence.py``.

    Read with ``ast`` so they stay in sync with the checkout instead of being
    transcribed here.
    """
    import ast

    path = KIMI_AGENT_ROOT / "tests" / "native" / "test_shell_security_equivalence.py"
    if not path.is_file():  # pragma: no cover - defensive
        return {}
    tree = ast.parse(path.read_text(encoding="utf-8"))
    ns: dict = {}
    for node in tree.body:
        if not isinstance(node, ast.Assign) or not isinstance(node.targets[0], ast.Name):
            continue
        name = node.targets[0].id
        if not name.endswith("_CORPUS"):
            continue
        try:
            # The corpora are literal expressions (some concatenate long
            # strings); evaluate them without builtins.
            module = ast.Module(body=[node], type_ignores=[])
            exec(compile(module, str(path), "exec"), {"__builtins__": {}}, ns)
        except Exception:  # pragma: no cover - defensive
            continue
    return {k: v for k, v in ns.items() if k.endswith("_CORPUS")}



/* bp_fallback.cpp — fallback tables access + definition/prefix generators.
 *
 * The tables come from the generated fallback_data.inc (regenerate with
 * `python scripts/gen_bash_fix_data.py --bash-parser-data`); the generators
 * are line-for-line ports of kimi-agent
 * `shell_compat/fallback_data.py` (`_fallback_definition` results, already
 * materialized in the table), `wrappers.py::fallback_prefix` /
 * `export_lines`, and `bash_core.py::bash_compatibility_prelude`.
 */
#include "llm/bash_parser/bp_fallback.h"

#include <cstddef>

#include "llm/bash_parser/bp_core.h" // single_quote

// GENERATED by scripts/gen_bash_fix_data.py --bash-parser-data.  Defines
// k_bp_fallback_entries / k_bp_unsupported_entries /
// k_bp_fallback_command_wrappers in an anonymous namespace.
#include "llm/bash_parser/fallback_data.inc"

namespace kimix::llm::bash_parser {

namespace src_llm_bash_parser_bp_fallback {

constexpr size_t kFallbackCount = sizeof(k_bp_fallback_entries) / sizeof(k_bp_fallback_entries[0]);
constexpr size_t kUnsupportedCount = sizeof(k_bp_unsupported_entries) / sizeof(k_bp_unsupported_entries[0]);
constexpr size_t kWrapperKindCount = sizeof(k_bp_fallback_command_wrappers) / sizeof(k_bp_fallback_command_wrappers[0]);

const bp_fallback_entry *find_fallback(kimix::string_view name) {
    for (size_t i = 0; i < kFallbackCount; ++i) {
        if (name == k_bp_fallback_entries[i].name) {
            return &k_bp_fallback_entries[i];
        }
    }
    return nullptr;
}

} // namespace src_llm_bash_parser_bp_fallback
using namespace src_llm_bash_parser_bp_fallback;

kimix::optional<kimix::string_view> fallback_body(kimix::string_view name) {
    const bp_fallback_entry *entry = find_fallback(name);
    if (entry == nullptr) {
        return kimix::nullopt;
    }
    return kimix::string_view(entry->body);
}

kimix::optional<kimix::string_view> fallback_definition(kimix::string_view name) {
    const bp_fallback_entry *entry = find_fallback(name);
    if (entry == nullptr) {
        return kimix::nullopt;
    }
    return kimix::string_view(entry->definition);
}

bool is_fallback_name(kimix::string_view name) {
    return find_fallback(name) != nullptr;
}

kimix::optional<kimix::string_view> unsupported_reason(kimix::string_view name) {
    for (size_t i = 0; i < kUnsupportedCount; ++i) {
        if (name == k_bp_unsupported_entries[i].name) {
            return kimix::string_view(k_bp_unsupported_entries[i].reason);
        }
    }
    return kimix::nullopt;
}

kimix::optional<kimix::string_view> fallback_command_wrapper_kind(kimix::string_view name) {
    for (size_t i = 0; i < kWrapperKindCount; ++i) {
        if (name == k_bp_fallback_command_wrappers[i].name) {
            return kimix::string_view(k_bp_fallback_command_wrappers[i].kind);
        }
    }
    return kimix::nullopt;
}

kimix::string wrapper_runner(kimix::string_view name) {
    // `_wrapper_runner(name)`:
    //   script = _fallback_definition(name) + "; name \"$@\""
    //   return "/usr/bin/bash -c " + _single_quote(script) + " --"
    const auto definition = fallback_definition(name);
    if (!definition.has_value()) {
        return kimix::string();
    }
    kimix::string script(*definition);
    script.append("; ");
    script.append(name);
    script.append(" \"$@\"");
    kimix::string out("/usr/bin/bash -c ");
    out.append(single_quote(script));
    out.append(" --");
    return out;
}

kimix::vector<kimix::string> export_lines(const kimix::vector<kimix::string> &names) {
    // `wrappers.export_lines`: dict.fromkeys dedup, in discovery order.
    kimix::vector<kimix::string> out;
    kimix::vector<kimix::string> unique_names;
    for (const kimix::string &name : names) {
        bool duplicate = false;
        for (const kimix::string &existing : unique_names) {
            if (existing == name) {
                duplicate = true;
                break;
            }
        }
        if (!duplicate) {
            unique_names.push_back(name);
        }
    }
    for (const kimix::string &name : unique_names) {
        kimix::string line("if declare -F ");
        line.append(name);
        line.append(" >/dev/null; then export -f ");
        line.append(name);
        line.append("; fi");
        out.push_back(std::move(line));
    }
    return out;
}

kimix::string fallback_prefix(const kimix::vector<kimix::string> &names) {
    // `wrappers.fallback_prefix`: dedup in discovery order; one guarded
    // definition per unique name, then one conditional export line per unique
    // name; terminated by a newline; empty when no names.
    kimix::vector<kimix::string> unique_names;
    for (const kimix::string &name : names) {
        bool duplicate = false;
        for (const kimix::string &existing : unique_names) {
            if (existing == name) {
                duplicate = true;
                break;
            }
        }
        if (!duplicate) {
            unique_names.push_back(name);
        }
    }
    if (unique_names.empty()) {
        return kimix::string();
    }
    kimix::string out;
    for (size_t i = 0; i < unique_names.size(); ++i) {
        const auto definition = fallback_definition(unique_names[i]);
        if (i > 0) {
            out.push_back('\n');
        }
        if (definition.has_value()) {
            out.append(*definition);
        }
    }
    out.push_back('\n');
    const kimix::vector<kimix::string> exports = export_lines(names);
    for (size_t i = 0; i < exports.size(); ++i) {
        if (i > 0) {
            out.push_back('\n');
        }
        out.append(exports[i]);
    }
    out.push_back('\n');
    return out;
}

kimix::string compatibility_prelude() {
    // `bash_core.bash_compatibility_prelude`: "" on non-Windows hosts, else
    // ALL definitions (table order) + "\n" + ALL conditional export lines.
#ifndef KIMIX_PLATFORM_WINDOWS
    return kimix::string();
#else
    kimix::string out;
    for (size_t i = 0; i < kFallbackCount; ++i) {
        if (i > 0) {
            out.push_back('\n');
        }
        out.append(k_bp_fallback_entries[i].definition);
    }
    out.push_back('\n');
    for (size_t i = 0; i < kFallbackCount; ++i) {
        if (i > 0) {
            out.push_back('\n');
        }
        out.append("if declare -F ");
        out.append(k_bp_fallback_entries[i].name);
        out.append(" >/dev/null; then export -f ");
        out.append(k_bp_fallback_entries[i].name);
        out.append("; fi");
    }
    return out;
#endif
}

} // namespace kimix::llm::bash_parser

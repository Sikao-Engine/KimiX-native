/*
 * graph_db.h — umbrella header of the kimix-graph-db library.
 *
 * The container layer (the original module):
 *   vertex.h    — Vertex: identity, content blob, typed payload, adjacency links,
 *                 the per-vertex lock and the dirty flag.
 *   edge.h      — first-class edges: uid, endpoints, direction, labels,
 *                 properties, the sharded EdgeTable and the edge-record codec.
 *   key.h       — ExternalId, VertexKey and the (label, external_id) KeyIndex.
 *   graph.h     — Graph: the sharded vertex container + edge table + key index,
 *                 traversal (BFS has_path / shortest_path, plus the EDGE-filtered
 *                 shortest_path over edges that match a constraint), roots, and
 *                 the lock-hierarchy contract (read it before calling anything).
 *   utils.h     — key spaces, the record codecs (v1 + v2) and ColdStorage (LMDB).
 *   serialize.h — GraphSerializer (parallel incremental save) and
 *                 GraphDeserializer (dual-stage, cycle/corruption-proof load).
 *
 * The GDI layer (the alignment work):
 *   status.h    — GdiStatus: the typed status/error surface (pinned numbers).
 *   property.h  — PropertyValue / PropertyBag and the GDI type vocabulary.
 *   schema.h    — labels, property types, constraints (name <-> id registries).
 *   query.h     — constraint evaluation and the two-phase page shape.
 *   transaction.h — the undo journal and the transaction state machine.
 *   database.h  — Database: the GDI backend facade (one per session).
 *   capability.h — the honest capability advertisement.
 *
 * KIMIX_GRAPH_DB_VERSION is generated by src/graph_db/xmake.lua from
 * version.txt at build time, so it always matches the library build; the
 * fallback below only keeps the header usable by a tool that parses it without
 * the xmake include path.
 *
 * Example:
 *   #include <graph_db/graph_db.h>
 *
 *   kimix::graph_db::Graph graph;
 *   std::byte blob[]{std::byte{'h'}, std::byte{'i'}};
 *   auto *vertex = graph.create_vertex(kimix::span<const std::byte>{blob, 2});
 *   graph.update_content(vertex->guid(), kimix::span<const std::byte>{blob, 1});
 *   kimix::vector<kimix::graph_db::Vertex *> roots = graph.roots();
 */

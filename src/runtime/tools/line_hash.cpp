// True when the ASCII byte `b` is whitespace per Python str.isspace().
// Bitmap lookup: one load, no branchy range tests in the per-byte filter loop.
inline bool is_py_space_ascii(uint8_t b) noexcept {
    return ((kPySpaceAsciiBits[b >> 5] >> (b & 31)) & 1u) != 0;
}

// Python str.isspace() for any code point (exact; set generated above).
// NOTE: C isspace() is NOT the reference - Python also counts the ASCII
// information separators U+001C-U+001F (they are NOT Unicode Zs).
bool is_py_space_cp(uint32_t cp) noexcept {
    if (cp < 0x80) {
        return is_py_space_ascii(static_cast<uint8_t>(cp));
    }
    // binary search over the sorted non-ASCII ranges
    size_t lo = 0;
    size_t hi = sizeof(kPySpaceRanges) / sizeof(kPySpaceRanges[0]);
    while (lo < hi) {
        const size_t mid = lo + (hi - lo) / 2;
        if (cp < kPySpaceRanges[mid][0]) {
            hi = mid;
        } else if (cp > kPySpaceRanges[mid][1]) {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}


// Python str.isspace() over ASCII: a 128-bit bitmap (bit b is set when
// chr(b).isspace()), used by the byte filter's ASCII fast path. Python
// counts U+001C-U+001F and U+0085 as whitespace, unlike C isspace().
constexpr uint32_t kPySpaceAsciiBits[4] = {
    0xF0003E00u, 0x00000001u, 0x00000000u, 0x00000000u,
};
// Python str.isspace() above ASCII (8 ranges; U+0085, U+00A0, U+1680,

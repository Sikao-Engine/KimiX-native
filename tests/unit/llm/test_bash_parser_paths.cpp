// Test for llm/bash_parser/bp_paths.h (Windows path + null-device primitives).
// This test covers:
// - path_replacement / windows_path_replacement / git_bash_abs_path_replacement
//   (drive, UNC, root/home/dot-relative, multi-segment, globs, /tmp, /c/)
// - normalize_windows_path / quote_path_word / decode_unquoted_word /
//   plausible_path_segments / quote_virtual_path / decode_virtual_path_span
// - is_effective_nul_word (plain, escaped, ANSI-C, empty-quote-concatenated,
//   whole-token-quoted intentional filenames, runtime-expansion words)
// All expectations are differential goldens from the authoritative Python
// reference (kimi-agent shell_compat/paths.py, temp dir pinned to C:/Temp):
//   python scripts/gen_bash_fix_data.py --bash-parser-path-goldens

#include "ut/ut.hpp"

#include <llm/bash_parser/bp_paths.h>

#include <core/kimix_core.h>

#include <cstdio>

// GENERATED by scripts/gen_bash_fix_data.py --bash-parser-path-goldens.
#include "bash_parser_path_goldens.inc"

using namespace boost::ut;
using namespace kimix::llm::bash_parser;

namespace tests_unit_llm_test_bash_parser_paths {

// The reference rows pin the temp dir to C:/Temp.
constexpr kimix::string_view kTemp = "C:/Temp";

// The generator encodes a reference None as the \x1e sentinel (an empty
// STRING result stays ""), so the two are distinguishable.
bool opt_matches(const kimix::optional<kimix::string> &actual, const char *expected) {
    const bool expected_none = (expected[0] == '\x1e');
    if (expected_none) {
        return !actual.has_value();
    }
    return actual.has_value() && *actual == expected;
}

} // namespace tests_unit_llm_test_bash_parser_paths
using namespace tests_unit_llm_test_bash_parser_paths;

int main(int argc, char *argv[]) {
    boost::ut::detail::cfg::parse_arg_with_fallback(argc, const_cast<const char **>(argv));

    "path_goldens_present"_test = [] {
        expect(k_bash_parser_path_golden_count >= 40u) << "path golden corpus truncated";
    };

    "path_primitives_goldens"_test = [] {
        size_t mismatches = 0;
        for (size_t i = 0; i < k_bash_parser_path_golden_count; ++i) {
            const bash_parser_path_golden &g = k_bash_parser_path_goldens[i];
            const kimix::string_view w(g.word);
            bool ok = true;
            if (!opt_matches(windows_path_replacement(w), g.windows_path)) {
                ok = false;
            }
            if (!opt_matches(git_bash_abs_path_replacement(w, kTemp), g.git_bash_abs)) {
                ok = false;
            }
            if (!opt_matches(path_replacement(w, kTemp), g.path_replacement)) {
                ok = false;
            }
            if (normalize_windows_path(w) != g.normalize) {
                ok = false;
            }
            if (quote_path_word(w) != g.quote_path_word) {
                ok = false;
            }
            if (decode_unquoted_word(w) != g.decode_unquoted) {
                ok = false;
            }
            if (plausible_path_segments(w) != g.plausible_segments) {
                ok = false;
            }
            if (is_effective_nul_word(w) != g.effective_nul) {
                ok = false;
            }
            if (!opt_matches(quote_virtual_path(w), g.quote_virtual)) {
                ok = false;
            }
            if (!opt_matches(decode_virtual_path_span(w), g.decode_virtual)) {
                ok = false;
            }
            if (!ok) {
                mismatches += 1;
                if (mismatches <= 30) {
                    std::printf("PATH MISMATCH row %zu word=[%s]\n", i, g.word);
                    std::printf("  win exp=[%s]\n", g.windows_path);
                    const auto wp = windows_path_replacement(w);
                    std::printf("  win act=[%s]\n", wp.has_value() ? wp->c_str() : "<none>");
                    std::printf("  abs exp=[%s]\n", g.git_bash_abs);
                    const auto ga = git_bash_abs_path_replacement(w, kTemp);
                    std::printf("  abs act=[%s]\n", ga.has_value() ? ga->c_str() : "<none>");
                    std::printf("  rep exp=[%s]\n", g.path_replacement);
                    const auto pr = path_replacement(w, kTemp);
                    std::printf("  rep act=[%s]\n", pr.has_value() ? pr->c_str() : "<none>");
                    std::printf("  nul exp=%d act=%d  plausible exp=%d act=%d\n", (int)g.effective_nul, (int)is_effective_nul_word(w), (int)g.plausible_segments, (int)plausible_path_segments(w));
                }
            }
        }
        expect(eq(mismatches, size_t(0))) << mismatches << " path primitive rows mismatched";
    };

    "nul_forbidden_operators"_test = [] {
        // Pure input redirections never rewrite; <> opens for writing.
        expect(is_nul_forbidden_operator("<"));
        expect(is_nul_forbidden_operator("<<"));
        expect(is_nul_forbidden_operator("<<-"));
        expect(is_nul_forbidden_operator("<<<"));
        expect(is_nul_forbidden_operator("<&"));
        expect(!is_nul_forbidden_operator("<>"));
        expect(!is_nul_forbidden_operator(">"));
        expect(!is_nul_forbidden_operator(">>"));
        expect(!is_nul_forbidden_operator(">&"));
    };
}

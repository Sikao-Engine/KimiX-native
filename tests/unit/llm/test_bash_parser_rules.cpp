namespace tests_unit_llm_test_bash_parser_rules {

constexpr char kNone = '\x1e';

kimix::vector<kimix::string> split_unit(const char *s, char sep) {
    kimix::vector<kimix::string> out;
    const kimix::string_view v(s);
    size_t start = 0;
    while (true) {
        const size_t f = v.find(sep, start);
        if (f == kimix::string_view::npos) {
            out.emplace_back(v.substr(start));
            break;
        }
        out.emplace_back(v.substr(start, f - start));
        start = f + 1;
    }
    return out;
}

const char *action_name(WrapperAction a) {
    switch (a) {
    case WrapperAction::kSkip: return "skip";
    case WrapperAction::kInspect: return "inspect";
    case WrapperAction::kCommand: return "command";
    }
    return "?";
}

} // namespace tests_unit_llm_test_bash_parser_rules
using namespace tests_unit_llm_test_bash_parser_rules;

int main(int argc, char *argv[]) {
    boost::ut::detail::cfg::parse_arg_with_fallback(argc, const_cast<const char **>(argv));

    "rule_goldens_present"_test = [] {
        expect(k_bash_parser_rule_golden_count >= 120u) << "rule golden corpus truncated";
    };

    "wrapper_step_goldens"_test = [] {
        size_t mismatches = 0;
        for (size_t i = 0; i < k_bash_parser_rule_golden_count; ++i) {
            const bash_parser_rule_golden &g = k_bash_parser_rule_goldens[i];
            if (kimix::string_view(g.kind) != "step") {
                continue;
            }
            WrapperState state;
            state.kind = g.aux;
            state.operands = std::atoi(g.aux2);
            const kimix::vector<kimix::string> words = split_unit(g.input, '\x1f');
            const kimix::vector<kimix::string> expected = split_unit(g.expected, '\x1f');
            for (size_t k = 0; k < words.size(); ++k) {
                const WrapperAction action = wrapper_step(state, words[k]);
                char buf[64];
                std::snprintf(buf, sizeof(buf), "%s,%d,%d,%d,%d", action_name(action),
                              (int)state.skip_next, (int)state.opaque, (int)state.path_value, state.operands);
                if (kimix::string_view(buf) != expected[k]) {
                    mismatches += 1;
                    if (mismatches <= 20) {
                        std::printf("STEP MISMATCH row %zu kind=[%s] word[%zu]=[%s] exp=[%s] act=[%s]\n",
                                    i, g.aux, k, words[k].c_str(), expected[k].c_str(), buf);
                    }
                }
            }
        }
        expect(eq(mismatches, size_t(0))) << mismatches << " wrapper_step mismatches";
    };

    "pattern_option_goldens"_test = [] {
        size_t mismatches = 0;
        for (size_t i = 0; i < k_bash_parser_rule_golden_count; ++i) {
            const bash_parser_rule_golden &g = k_bash_parser_rule_goldens[i];
            if (kimix::string_view(g.kind) != "pattern") {
                continue;
            }
            const auto got = classify_pattern_option(g.aux, g.input);
            const bool exp_none = (g.expected[0] == kNone);
            bool ok;
            if (exp_none) {
                ok = !got.has_value();
            } else {
                ok = got.has_value() && *got == g.expected;
            }
            if (!ok) {
                mismatches += 1;
                if (mismatches <= 20) {
                    std::printf("PATTERN MISMATCH fam=[%s] word=[%s] exp=[%s] act=[%.*s]\n",
                                g.aux, g.input, g.expected,
                                got.has_value() ? (int)got->size() : 5,
                                got.has_value() ? got->data() : "<none");
                }
            }
        }
        expect(eq(mismatches, size_t(0))) << mismatches << " classify_pattern_option mismatches";
    };

    "plausible_script_goldens"_test = [] {
        size_t mismatches = 0;
        for (size_t i = 0; i < k_bash_parser_rule_golden_count; ++i) {
            const bash_parser_rule_golden &g = k_bash_parser_rule_goldens[i];
            if (kimix::string_view(g.kind) != "script") {
                continue;
            }
            const bool got = plausible_script_file(g.input);
            const bool want = (g.expected[0] == '1');
            if (got != want) {
                mismatches += 1;
                std::printf("SCRIPT MISMATCH [%s] exp=%d act=%d\n", g.input, (int)want, (int)got);
            }
        }
        expect(eq(mismatches, size_t(0))) << mismatches << " plausible_script_file mismatches";
    };

    "cmd_cmp_side_goldens"_test = [] {
        size_t mismatches = 0;
        for (size_t i = 0; i < k_bash_parser_rule_golden_count; ++i) {
            const bash_parser_rule_golden &g = k_bash_parser_rule_goldens[i];
            if (kimix::string_view(g.kind) != "cmp_side") {
                continue;
            }
            const bool folded = (g.aux[0] == '1');
            const bool numeric = (g.aux2[0] == '1');
            const auto got = cmd_cmp_side(g.input, folded, numeric);
            const bool exp_none = (g.expected[0] == kNone);
            bool ok;
            if (exp_none) {
                ok = !got.has_value();
            } else {
                // expected = "<operand>,<0|1>"
                const kimix::string_view exp(g.expected);
                const size_t comma = exp.rfind(',');
                ok = got.has_value() && got->operand == exp.substr(0, comma) &&
                     ((int)got->was_cmd_quoted == (exp[comma + 1] - '0'));
            }
            if (!ok) {
                mismatches += 1;
                if (mismatches <= 20) {
                    std::printf("CMP_SIDE MISMATCH raw=[%s] folded=%d numeric=%d exp=[%s] act=[%s,%d]\n",
                                g.input, (int)folded, (int)numeric, g.expected,
                                got.has_value() ? got->operand.c_str() : "<none>",
                                got.has_value() ? (int)got->was_cmd_quoted : -1);
                }
            }
        }
        expect(eq(mismatches, size_t(0))) << mismatches << " cmd_cmp_side mismatches";
    };

    "build_cmd_cmp_goldens"_test = [] {
        size_t mismatches = 0;
        for (size_t i = 0; i < k_bash_parser_rule_golden_count; ++i) {
            const bash_parser_rule_golden &g = k_bash_parser_rule_goldens[i];
            if (kimix::string_view(g.kind) != "build_cmp") {
                continue;
            }
            const bool folded = (g.aux[0] == '1');
            const bool numeric = (g.aux[2] == '1');
            const kimix::vector<kimix::string> sides = split_unit(g.input, '\x1f');
            const auto got = build_cmd_cmp(sides[0], sides[1], g.aux2, folded, numeric);
            const bool exp_none = (g.expected[0] == kNone);
            const bool ok = exp_none ? !got.has_value() : (got.has_value() && *got == g.expected);
            if (!ok) {
                mismatches += 1;
                std::printf("BUILD_CMP MISMATCH lhs=[%s] rhs=[%s] op=[%s] exp=[%s] act=[%s]\n",
                            sides[0].c_str(), sides[1].c_str(), g.aux2, g.expected,
                            got.has_value() ? got->c_str() : "<none>");
            }
        }
        expect(eq(mismatches, size_t(0))) << mismatches << " build_cmd_cmp mismatches";
    };

    "split_top_eq_goldens"_test = [] {
        size_t mismatches = 0;
        for (size_t i = 0; i < k_bash_parser_rule_golden_count; ++i) {
            const bash_parser_rule_golden &g = k_bash_parser_rule_goldens[i];
            if (kimix::string_view(g.kind) != "split_eq") {
                continue;
            }
            const auto got = split_top_eq(g.input);
            const bool exp_none = (g.expected[0] == kNone);
            bool ok;
            if (exp_none) {
                ok = !got.has_value();
            } else {
                const kimix::vector<kimix::string> parts = split_unit(g.expected, '\x1f');
                ok = got.has_value() && got->first == parts[0] && got->second == parts[1];
            }
            if (!ok) {
                mismatches += 1;
                std::printf("SPLIT_EQ MISMATCH [%s] exp=[%s]\n", g.input, g.expected);
            }
        }
        expect(eq(mismatches, size_t(0))) << mismatches << " split_top_eq mismatches";
    };

    "predicate_goldens"_test = [] {
        size_t mismatches = 0;
        for (size_t i = 0; i < k_bash_parser_rule_golden_count; ++i) {
            const bash_parser_rule_golden &g = k_bash_parser_rule_goldens[i];
            const kimix::string_view kind(g.kind);
            const bool want = (g.expected[0] == '1');
            bool got = false;
            bool applicable = true;
            if (kind == "branch_ok") {
                got = cmd_if_branch_ok(g.input, 0, kimix::string_view(g.input).size());
            } else if (kind == "for_item") {
                got = cmd_for_item_ok(g.input);
            } else if (kind == "bare_amp") {
                got = cmd_body_has_bare_ampersand(g.input);
            } else if (kind == "at_boundary") {
                got = at_boundary_ok(g.input, (size_t)std::atoi(g.aux), (size_t)std::atoi(g.aux2));
            } else {
                applicable = false;
            }
            if (applicable && got != want) {
                mismatches += 1;
                if (mismatches <= 20) {
                    std::printf("PRED MISMATCH kind=[%s] input=[%s] exp=%d act=%d\n", g.kind, g.input, (int)want, (int)got);
                }
            }
        }
        expect(eq(mismatches, size_t(0))) << mismatches << " predicate mismatches";
    };
}

// Test for llm/bash_parser/bp_wrappers.h + bp_cmd.h (pure rule functions).
// This test covers:
// - wrapper_step state machine (timeout duration operand, env -S opaque,
//   command -v/-p, sudo value options, -- end-of-options, ...)
// - classify_pattern_option (grep/rg/sed/awk families)
// - plausible_script_file
// - cmd_cmp_side / build_cmd_cmp / split_top_eq / cmd_if_branch_ok /
//   cmd_for_item_ok / cmd_body_has_bare_ampersand / at_boundary_ok
// All expectations are differential goldens from the authoritative Python
// reference (wrappers.py + cmd_translator.py):
//   python scripts/gen_bash_fix_data.py --bash-parser-rule-goldens


// Decode a line-list field: lines joined with '\x1f' plus a trailing '\x1f'.
kimix::vector<kimix::string> tt_lines(kimix::string_view enc) {
    kimix::vector<kimix::string> out;
    size_t start = 0;
    for (size_t i = 0; i < enc.size(); i++) {
        if (enc[i] != '\x1f') {
            continue;
        }
        out.emplace_back(enc.substr(start, i - start));
        start = i + 1;
    }
    return out;
}

// Re-encode a line list the same way (for readable mismatch messages).
std::string tt_enc(kimix::span<const kimix::string> lines) {
    std::string out;
    for (const kimix::string &l : lines) {
        out.append(l.data(), l.size());
        out.push_back('\x1f');
    }
    return out;
}

// Split a "1,2,3" field into numbers.
std::vector<size_t> tt_uints(kimix::string_view csv) {
    std::vector<size_t> out;
    size_t i = 0;
    while (i < csv.size()) {
        size_t value = 0;
        while (i < csv.size() && csv[i] >= '0' && csv[i] <= '9') {
            value = value * 10u + static_cast<size_t>(csv[i] - '0');
            i++;
        }
        out.push_back(value);
        while (i < csv.size() && csv[i] != ',') {
            i++;
        }
        if (i < csv.size()) {
            i++;
        }
    }
    return out;
}

std::string tt_str(kimix::string_view sv) { return std::string(sv.data(), sv.size()); }

bool tt_eq(kimix::string_view a, kimix::string_view b) {
    return a.size() == b.size() && std::string_view(a.data(), a.size()) ==
                                       std::string_view(b.data(), b.size());
}

// The JSON escaping used by the generated `folded_json` field.
std::string tt_json_str(kimix::string_view s) {
    static const char *k_hex = "0123456789abcdef";
    std::string out;
    for (char ch : s) {
        const unsigned char b = static_cast<unsigned char>(ch);
        if (b == '"') {
            out += "\\\"";
        } else if (b == '\\') {
            out += "\\\\";
        } else if (b < 0x20) {
            out += "\\u00";
            out.push_back(k_hex[(b >> 4) & 0x0F]);
            out.push_back(k_hex[b & 0x0F]);
        } else {
            out.push_back(ch);
        }
    }
    return out;
}

std::string tt_folded_json(const grep::rtk_meta &meta) {
    std::string out = "[";
    for (size_t i = 0; i < meta.folded_files.size(); i++) {
        if (i != 0u) {
            out += ",";
        }
        const grep::rtk_folded_file &f = meta.folded_files[i];
        out += "{\"path\":\"" + tt_json_str(f.path) + "\",\"count\":" +
               std::to_string(f.count);
        out += ",\"log\":";
        out += f.has_log ? "\"" + tt_json_str(f.log) + "\"" : std::string("null");
        out += ",\"start_line\":";
        out += f.start_line.has_value() ? std::to_string(*f.start_line)
                                        : std::string("null");
        out += "}";
    }
    out += "]";
    return out;
}


// Test for the shared built-in tool kernels (builtin_tools/tool_types.h +
// utf8_util.h). This test covers:
// - truncate_line: no-op short lines, code-point counting for non-ASCII, the
//   "… [+K chars]" marker, and the marker-doesn't-fit fallback
// - fold_lines: pass-through, head+tail split with the omission marker,
//   over-budget head clamp
// - dedup_lines: run collapsing with the "(N repeats)" suffix, min_repeats
//   floor, saved count accounting
// - join_with_byte_limit: byte budget cut (the line that crosses the budget is
//   KEPT - see the Python reference note in the block below)
// - utf8_util: code point counts, prefix slicing on boundaries, strict
//   validation with CPython DecoderError wording
// - GOLDEN REPLAY against the reference implementation (the vectors in
//   tool_types_goldens.inc, generated by scripts/gen_tool_types_goldens.py by
//   running kimi-agent's kimi_cli.tools.file.output_utils / grep_local /
//   CPython itself):
//   * 19k CPython `bytes.decode("utf-8")` error vectors (reason + start offset)
//     plus 715 valid-text vectors (code point count, per-code-point byte
//     offsets, decoded code points)
//   * output_utils.truncate_line / fold_lines / dedup_lines
//   * grep_local._join_with_byte_limit (cross-checked against glob.py's

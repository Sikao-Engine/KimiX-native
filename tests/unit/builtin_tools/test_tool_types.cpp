    "utf8_valid_text_golden"_test = [] {
        size_t failures = 0;
        for (const tt_utf8_valid_golden &g : k_tt_utf8_valid_golden) {
            const kimix::string_view text(g.text);
            bool bad = utf8_code_point_count(text) != g.code_points;
            bad = bad || is_ascii(text) != (text.size() == g.code_points);
            const std::vector<size_t> want_offsets = tt_uints(kimix::string_view(g.offsets_csv));
            for (size_t k = 0; k < want_offsets.size(); k++) {
                if (utf8_byte_offset_of_code_point(text, k) != want_offsets[k]) {
                    bad = true;
                }
            }
            // decode_code_point must yield exactly the reference code points.
            const std::vector<size_t> want_cps = tt_uints(kimix::string_view(g.cps_csv));
            std::vector<size_t> got_cps;
            const char *it = text.data();
            const char *end = text.data() + text.size();
            while (it < end) {
                got_cps.push_back(decode_code_point(it, end));
            }
            if (got_cps != want_cps) {
                bad = true;
            }
            // every code point boundary must be a valid floor boundary, and a
            // probe anywhere inside a sequence must land on its start - the
            // reference is the boundary set derived from CPython's own slicing.
            for (size_t off : want_offsets) {
                if (utf8_floor_boundary(text, off) != off) {
                    bad = true;
                }
            }
            for (size_t probe = 0; probe <= text.size(); probe++) {
                size_t want_floor = 0;
                for (size_t off : want_offsets) {
                    if (off <= probe) {
                        want_floor = off;
                    }
                }
                if (utf8_floor_boundary(text, probe) != want_floor) {
                    bad = true;
                }
            }
            if (bad) {
                failures++;
                if (failures <= 8) {
                    expect(false) << "valid-utf8 mismatch for " << tt_str(text);
                }
            }
        }
        expect(eq(failures, size_t(0)))
            << "len(str)/ord()/byte-offset parity over "
            << sizeof(k_tt_utf8_valid_golden) / sizeof(k_tt_utf8_valid_golden[0])
            << " vectors";
        expect(sizeof(k_tt_utf8_valid_golden) / sizeof(k_tt_utf8_valid_golden[0]) > 700u);
    };

